import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

import type { ConfigLoader } from './load_config';
import { findDefaultConfig, importStudioModule } from './load_config';

/** Where a project without a config gets the one the Studio generates, ignored by git. */
export const GENERATED_CONFIG_DIR = '.isomer-studio';

/** Always ESM, so Node imports it as `import` whatever the project's `type`. */
const GENERATED_CONFIG_NAME = 'isomer-studio.config.mts';

/** Tried before the manifest's entries, so a pack runs from source without a build. */
const SOURCE_ENTRIES = [
  'src/index.tsx',
  'src/index.ts',
  'index.tsx',
  'index.ts',
] as const;

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === 'object' && value !== null;

interface Manifest {
  name?: unknown;
  type?: unknown;
  exports?: unknown;
  module?: unknown;
  main?: unknown;
}

const readManifest = (projectDir: string): Manifest => {
  const path = join(projectDir, 'package.json');
  if (!existsSync(path)) {
    throw new Error(
      `No package.json in ${projectDir}: run isomer-studio in a pack's package directory, or pass --config.`
    );
  }
  const manifest: unknown = JSON.parse(readFileSync(path, 'utf8'));
  return isRecord(manifest) ? manifest : {};
};

const rootExport = (exports: unknown): unknown => {
  const root = isRecord(exports) && '.' in exports ? exports['.'] : exports;
  return isRecord(root) ? (root.import ?? root.default ?? root.module) : root;
};

/** The module whose exports name the project's packs: its source index, else its manifest's root entry. */
export const packEntry = (projectDir: string): string => {
  const { exports, module, main } = readManifest(projectDir);
  const found = [...SOURCE_ENTRIES, rootExport(exports), module, main]
    .filter((path): path is string => typeof path === 'string')
    .map((path) => join(projectDir, path))
    .find((path) => existsSync(path));
  if (found === undefined) {
    throw new Error(
      `No pack entry in ${projectDir}: add ${SOURCE_ENTRIES.slice(0, 2).join(' or ')}, or pass --config.`
    );
  }
  return found;
};

/** Structural, since a pack carries no brand: what `definePrimitivePack` returns. `generatedConfigSource` inlines the same test. */
export const isPrimitivePack = (value: unknown): boolean =>
  isRecord(value) &&
  typeof value.id === 'string' &&
  Array.isArray(value.primitives) &&
  isRecord(value.types) &&
  typeof value.types.has === 'function';

/** A single-quoted string literal. */
const quote = (value: string): string =>
  `'${value.replace(/[\\']/g, (char) => `\\${char}`).replace(/\n/g, '\\n')}'`;

/** `path` from `fromDir`, as an import specifier. */
const specifierFrom = (fromDir: string, path: string): string => {
  const inside = relative(fromDir, path).split(sep).join('/');
  return inside.startsWith('.') ? inside : `./${inside}`;
};

const titleOf = (projectDir: string): string | undefined => {
  const { name } = readManifest(projectDir);
  return typeof name === 'string' ? name : undefined;
};

/** A config that registers every pack `entry` exports, named or on its default export. */
export const generatedConfigSource = ({
  entry,
  shownAs = entry,
  title,
}: {
  /** The entry, relative to the generated config. */
  entry: string;
  /** The entry as an error names it. */
  shownAs?: string | undefined;
  title?: string | undefined;
}): string =>
  [
    '// Generated by isomer-studio for a project without a config. `npx isomer-studio init` writes one to edit.',
    "import { createIsomerRuntime } from '@elastic/isomer-runtime';",
    '',
    `import * as entry from ${quote(entry)};`,
    '',
    "const isRecord = (value) => typeof value === 'object' && value !== null;",
    'const isPack = (value) =>',
    '  isRecord(value) &&',
    "  typeof value.id === 'string' &&",
    '  Array.isArray(value.primitives) &&',
    '  isRecord(value.types) &&',
    "  typeof value.types.has === 'function';",
    "const fallback = Reflect.get(entry, 'default');",
    'const exported = [',
    '  ...Object.values(entry),',
    '  ...(isRecord(fallback) ? Object.values(fallback) : []),',
    '];',
    'const packs = [...new Set(exported.filter(isPack))];',
    'if (packs.length === 0) {',
    `  throw new Error(${quote(`${shownAs} exports no primitive pack. Export one, or add an isomer-studio.config.ts.`)});`,
    '}',
    '',
    'export default {',
    ...(title === undefined ? [] : [`  title: ${quote(title)},`]),
    '  runtime: createIsomerRuntime({ packs }),',
    '};',
    '',
  ].join('\n');

const writeIfChanged = (path: string, contents: string): void => {
  if (!existsSync(path) || readFileSync(path, 'utf8') !== contents) {
    writeFileSync(path, contents);
  }
};

/** Writes the generated config for `projectDir` and returns its path and the entry it reads. */
export const writeGeneratedConfig = (
  projectDir: string
): { configPath: string; entry: string } => {
  const entry = packEntry(projectDir);
  const dir = join(projectDir, GENERATED_CONFIG_DIR);
  mkdirSync(dir, { recursive: true });
  writeIfChanged(join(dir, '.gitignore'), '*\n');
  const configPath = join(dir, GENERATED_CONFIG_NAME);
  const shownAs = specifierFrom(projectDir, entry);
  writeIfChanged(
    configPath,
    generatedConfigSource({
      entry: specifierFrom(dir, entry),
      shownAs,
      title: titleOf(projectDir),
    })
  );
  return { configPath, entry: shownAs };
};

/** How a config imports the packs a module exports. */
export interface PackImports {
  /** Named exports that are packs. */
  named: string[];
  /** Whether the default export is itself a pack. */
  isDefault: boolean;
  /** Packs on a default-exported object, as a CommonJS module exposes them. */
  onDefault: string[];
}

export const packImports = (namespace: unknown): PackImports => {
  const exports = isRecord(namespace) ? namespace : {};
  const { default: fallback } = exports;
  const packKeys = (record: Record<string, unknown>) =>
    Object.keys(record).filter(
      (key) => key !== 'default' && isPrimitivePack(record[key])
    );
  const named = packKeys(exports);
  const isDefault = isPrimitivePack(fallback);
  return {
    named,
    isDefault,
    onDefault:
      named.length || isDefault || !isRecord(fallback)
        ? []
        : packKeys(fallback),
  };
};

/** The config `init` writes: the packs `entry` exports, by name. */
export const initConfigSource = ({
  entry,
  imports: { named, isDefault, onDefault },
  title,
}: {
  entry: string;
  imports: PackImports;
  title?: string | undefined;
}): string => {
  const defaultName = isDefault ? 'pack' : onDefault.length ? 'entry' : '';
  const bindings = [
    defaultName,
    ...(named.length ? [`{ ${named.join(', ')} }`] : []),
  ].filter(Boolean);
  const packs = [
    ...(isDefault ? ['pack'] : []),
    ...named,
    ...onDefault.map((key) => `entry.${key}`),
  ];
  return [
    "import { createIsomerRuntime } from '@elastic/isomer-runtime';",
    "import { defineStudioConfig } from '@elastic/isomer-studio';",
    '',
    `import ${bindings.join(', ')} from ${quote(entry)};`,
    '',
    'export default defineStudioConfig({',
    ...(title === undefined ? [] : [`  title: ${quote(title)},`]),
    `  runtime: createIsomerRuntime({ packs: [${packs.join(', ')}] }),`,
    '});',
    '',
  ].join('\n');
};

const withoutTsExtension = (specifier: string): string =>
  specifier.replace(/\.tsx?$/, '');

/** Writes an editable config into `projectDir` naming the packs its entry exports, and returns its path. */
export const writeInitConfig = async (
  projectDir: string,
  { loader }: { loader?: ConfigLoader | undefined } = {}
): Promise<string> => {
  const existing = findDefaultConfig(projectDir);
  if (existing !== undefined) {
    throw new Error(`${existing} already exists.`);
  }
  const entry = packEntry(projectDir);
  const imports = packImports(await importStudioModule(entry, { loader }));
  if (
    !imports.named.length &&
    !imports.isDefault &&
    !imports.onDefault.length
  ) {
    throw new Error(
      `${specifierFrom(projectDir, entry)} exports no primitive pack.`
    );
  }
  const { type } = readManifest(projectDir);
  const configPath = join(
    projectDir,
    type === 'module' ? 'isomer-studio.config.ts' : 'isomer-studio.config.mts'
  );
  writeFileSync(
    configPath,
    initConfigSource({
      entry: withoutTsExtension(specifierFrom(projectDir, entry)),
      imports,
      title: titleOf(projectDir),
    })
  );
  return configPath;
};
