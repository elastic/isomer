// Writes `stylesheet.ts` from the installed Elastic Charts light stylesheet.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

const require = createRequire(import.meta.url);
const css = readFileSync(
  require.resolve('@elastic/charts/dist/theme_only_light.css'),
  'utf-8'
);
const [header] = readFileSync(new URL(import.meta.url), 'utf-8').split('\n\n');

const target = fileURLToPath(new URL('./stylesheet.ts', import.meta.url));
const source = `${header}

// Generated by \`pnpm studio:stylesheet\` from \`@elastic/charts/dist/theme_only_light.css\`.

/** Elastic Charts' light stylesheet, for the Studio's shadow-root previews. */
export const elasticChartsStylesheet = ${JSON.stringify(css)};
`;

writeFileSync(
  target,
  await format(source, {
    ...(await resolveConfig(target)),
    filepath: target,
  })
);
